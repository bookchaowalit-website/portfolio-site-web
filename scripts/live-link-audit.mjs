#!/usr/bin/env node
// Read-only live-link audit of every portfolio card: one HEAD (GET on 405/403) per demo
// and per GitHub source link, following redirects. Prints a Markdown report.
// Usage: node --experimental-strip-types scripts/live-link-audit.mjs > docs/audits/LIVE-LINK-AUDIT-<yyyy-mm>.md
import { allProjects, publicDemoUrl, publicSourceUrl } from "../src/data/app-projects.ts";

const CONCURRENCY = 6;
const TIMEOUT_MS = 20_000;

async function probe(url) {
  if (!url) return { status: "hidden", final: "" };
  for (const method of ["HEAD", "GET"]) {
    try {
      const res = await fetch(url, {
        method,
        redirect: "follow",
        signal: AbortSignal.timeout(TIMEOUT_MS),
        headers: { "User-Agent": "portfolio-live-link-audit (+https://bookchaowalit.com)" },
      });
      if (method === "HEAD" && (res.status === 405 || res.status === 403)) continue;
      return { status: res.status, final: res.url };
    } catch (error) {
      if (method === "GET") return { status: `error: ${error.cause?.code ?? error.name}`, final: "" };
    }
  }
  return { status: "error", final: "" };
}

async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: limit }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i]);
      }
    }),
  );
  return out;
}

const ok = (result) => result.status === "hidden" || result.status === 200;
const short = (url) => url.replace(/^https:\/\//, "");

const rows = await mapLimit(allProjects, CONCURRENCY, async (project) => {
  const demo = await probe(publicDemoUrl(project));
  const source = await probe(publicSourceUrl(project));
  return { project, demo, source };
});

const broken = rows.filter((row) => !ok(row.demo) || !ok(row.source));
const count = (pick, value) => rows.filter((row) => pick(row) === value).length;
const date = new Date().toISOString().slice(0, 10);

const lines = [
  `# Live-link audit (${date})`,
  "",
  "Generated by `scripts/live-link-audit.mjs` from `src/data/app-projects.ts`: one read-only HEAD/GET per",
  "card's demo URL and GitHub URL, following redirects. `hidden` means the card publishes no link",
  "(`demoUnavailable`, or no public `repo`), so nothing is shown to visitors.",
  "",
  "## Summary",
  "",
  "| Measure | Count |",
  "|---|---:|",
  `| Cards | ${rows.length} |`,
  `| Demo links returning 200 | ${count((row) => row.demo.status, 200)} |`,
  `| Demo links hidden | ${count((row) => row.demo.status, "hidden")} |`,
  `| Source links returning 200 | ${count((row) => row.source.status, 200)} |`,
  `| Source links hidden | ${count((row) => row.source.status, "hidden")} |`,
  `| Cards with a broken published link | ${broken.length} |`,
  "",
  "## Every card",
  "",
  "| Card | Status | Demo | Demo result | Source | Source result |",
  "|---|---|---|---|---|---|",
  ...rows.map(({ project, demo, source }) => {
    const demoUrl = publicDemoUrl(project);
    const redirect = demo.final && demo.final.replace(/\/$/, "") !== demoUrl.replace(/\/$/, "") ? ` → ${short(demo.final)}` : "";
    return `| ${project.slug} | ${project.status} | ${demoUrl ? short(demoUrl) : "—"} | ${demo.status}${redirect} | ${project.repo ?? "—"} | ${source.status} |`;
  }),
  "",
];

process.stdout.write(lines.join("\n"));
process.exitCode = broken.length ? 1 : 0;
